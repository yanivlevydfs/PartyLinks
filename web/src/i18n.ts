  software_dev: "Software development", cloud_devops: "Cloud & DevOps", web3: "Web3 & Blockchain", happy_hour: "Happy Hour",
  dark_wave: "Dark Wave / Synth", yoga_wellness: "Yoga & Wellness", liberal: "Liberal / Swingers", kink: "BDSM / Fetish",
